/** A statement of the given rows, oldest first, written the way the bank exports it. */
export function jarStatementOf(entries: readonly Entry[]): string {
  let balance = 500_000;
  const lines = entries.map(([dateTime, amount, comment]) => {
    const kopiykas = Math.round(Number(amount) * 100);
    balance += comment === WITHDRAWAL ? -kopiykas : kopiykas;
    const category = comment === WITHDRAWAL ? JAR_WITHDRAWAL_CATEGORY : JAR_DEPOSIT_CATEGORY;
    const details = comment === WITHDRAWAL ? 'На чорну картку' : 'З Чорної картки';
    return `${dateTime},${category},${amount},UAH,"${details}","${comment ?? ''}",${(balance / 100).toFixed(2)},UAH`;
  });
  // The bank lists the newest row first.
  return [JAR_STATEMENT_HEADER, ...lines.reverse()].join('\n') + '\n';
}

